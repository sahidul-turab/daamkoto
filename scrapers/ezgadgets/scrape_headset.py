"""
EZ Gadgets Headset scraper — WooCommerce Store API, with a DOM fallback.

Primary path : /wp-json/wc/store/v1/products?category=<id>&per_page=100
Fallback path: the Woodmart category archive, cards at `.wd-product`

Generated by scrapers/gen_ezgadgets_scrapers.py — edit the generator, not this.

Usage:
  python scrapers/ezgadgets/scrape_headset.py           # print only
  python scrapers/ezgadgets/scrape_headset.py --save    # save JSON to data/raw/
  python scrapers/ezgadgets/scrape_headset.py --dom     # force the fallback
"""

import argparse
import asyncio
import html
import io
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

from playwright.async_api import async_playwright, TimeoutError as PlaywrightTimeout

BASE_URL      = "https://ggezgadgets.com"
CATEGORY_SLUG = "headset"
ARCHIVE_URL   = f"{BASE_URL}/product-category/peripherals/headset/"

# Cloudflare fronts this shop. It served us plain 200s throughout development,
# but the requests still go through a real browser context so that any cookie or
# challenge it does set is carried automatically — the same reason the Ryans
# scraper uses Playwright rather than `requests`.
USER_AGENT = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
              "(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36")

# Same stealth payload the Ryans scraper uses. Ryans is Cloudflare-protected too
# and pulls ~7,000 rows per nightly CI sweep, so this combination is known to
# clear Cloudflare from a GitHub Actions IP — it is not a guess.
_STEALTH_SCRIPT = """\
Object.defineProperty(navigator, 'webdriver', {get: () => undefined});
Object.defineProperty(navigator, 'plugins', {get: () => [1,2,3,4,5]});
window.chrome = {runtime: {}};
"""


async def _make_context(browser):
    ctx = await browser.new_context(
        user_agent=USER_AGENT,
        viewport={"width": 1400, "height": 1000},
    )
    await ctx.add_init_script(_STEALTH_SCRIPT)
    return ctx

PAGE_DELAY = 2.5    # seconds between requests — polite crawling
PER_PAGE   = 100    # Store API maximum
MAX_PAGES  = 60     # backstop against a paginator that never terminates
RETRIES    = 3      # attempts per request before giving up on it


class Blocked(Exception):
    """A request failed in a way that must not be mistaken for 'no more data'."""


async def _sleep_backoff(attempt: int) -> None:
    await asyncio.sleep(PAGE_DELAY * (2 ** attempt))


