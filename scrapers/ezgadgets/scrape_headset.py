def clean_price(raw: str) -> float | None:
    digits = re.sub(r"[^\d.]", "", raw.strip().split("\n")[0])
    try:
        val = float(digits) if digits else None
        return val if val else None
    except ValueError:
        return None


# One evaluate() per card instead of a dozen query_selector round trips.
CARD_JS = """el => {
    const a = el.querySelector('.wd-entities-title a') || el.querySelector('h3 a');
    if (!a) return null;
    const name = a.textContent.trim();
    if (!name) return null;

    const priceEl = el.querySelector('.price');
    const amounts = priceEl
        ? [...priceEl.querySelectorAll('.woocommerce-Price-amount')].map(e => e.textContent.trim())
        : [];
    const insEl = priceEl ? priceEl.querySelector('ins') : null;
    const insAmount = insEl
        ? (insEl.querySelector('.woocommerce-Price-amount') || insEl).textContent.trim()
        : null;

    // Woodmart lazy-loads listing images and, when a product has a gallery,
    // renders slides carrying data-image-url with no <img> at all.
    let image = '';
    for (const img of el.querySelectorAll('img')) {
        const v = img.getAttribute('data-src') || img.getAttribute('data-lazy')
               || img.getAttribute('src') || '';
        if (!v || v.startsWith('data:') || v.toLowerCase().endsWith('.svg')) continue;
        try { image = new URL(v, document.baseURI).href; } catch (e) {}
        if (image) break;
    }
    if (!image) {
        const slide = el.querySelector('.wd-product-grid-slide[data-image-url]');
        if (slide) {
            try { image = new URL(slide.getAttribute('data-image-url'), document.baseURI).href; }
            catch (e) {}
        }
    }

    const cls = el.className || '';
    return {
        name,
        product_url: a.href || null,
        amounts,
        ins_amount: insAmount,
        is_variable: cls.includes('product-type-variable'),
        out_of_stock: cls.includes('outofstock'),
        image_url: image || null,
    };
}"""


def pick_price(rec: dict) -> tuple[float | None, float | None]:
    """Return (price, price_max). price_max is set only for a variable range.

    Read the amount elements, never `.price` text: the sale markup interleaves
    screen-reader copy ("Original price was: ...") with the numbers.
      plain    -> one amount
      on sale  -> <del> old, <ins> new; take <ins>
      variable -> "low - high"; take low, the "from" price, and keep high
    """
    if rec.get("ins_amount"):
        price = clean_price(rec["ins_amount"])
        if price:
            return price, None

    amounts = [p for p in (clean_price(a) for a in rec.get("amounts") or []) if p]
    if not amounts:
        return None, None
    if rec.get("is_variable") and len(amounts) > 1:
        return min(amounts), max(amounts)
    return amounts[0], None


async def scrape_archive_page(page, url: str) -> list[dict]:
    """Records on one archive page. Raises Blocked if the grid never renders.

    There is no 'empty page' case here: the caller reads the real page count
    from page 1's pagination and never requests a page past it, so a missing
    product grid always means blocked. Guessing 'empty vs blocked' from the
    markup was tried and got it wrong — a one-page category's page 2 was read as
    a block, which failed 14 complete scrapes.
    """
    await page.goto(url, wait_until="domcontentloaded", timeout=60_000)
    try:
        await page.wait_for_selector(".wd-product", timeout=15_000)
    except PlaywrightTimeout:
        raise Blocked(f"no product grid at {url}")

    for y in [400, 900, 1600]:
        await page.evaluate(f"window.scrollTo(0, {y})")
        await page.wait_for_timeout(300)
    await page.wait_for_timeout(500)

    products = []
    scraped_at = datetime.now(timezone.utc).isoformat()

    for card in await page.query_selector_all(".wd-product"):
        rec = await card.evaluate(CARD_JS)
        if not rec:
            continue

        price, price_max = pick_price(rec)
        in_stock = (not rec["out_of_stock"]) and price is not None

        inline_specs = {}
        if price_max is not None:
            inline_specs["price_from"] = price
            inline_specs["price_max"] = price_max

        products.append({
            "image_url": rec["image_url"],
            "name": rec["name"],
            "price_bdt": price,
            "in_stock": in_stock,
            "stock_status": "in_stock" if in_stock else "out_of_stock",
            "product_url": rec["product_url"],
            "inline_specs": inline_specs,
            "source": "EZGadgets",
            "pc_bundle_only": False,
            "scraped_at": scraped_at,
        })

    return products


async def _fetch_one_page(browser, page_num: int, want_count: bool):
    """Fetch one archive page in a **fresh browser context**, with retries.

    Reusing one context across pages makes Cloudflare re-issue its challenge and
    the scrape dies — the same behaviour documented for Ryans in CLAUDE.md. A
    context per page is slower and reliable; Ryans pulls ~7,000 rows a night
    from CI this way.
    """
    url = ARCHIVE_URL if page_num == 1 else f"{ARCHIVE_URL}page/{page_num}/"
    print(f"Scraping page {page_num}: {url}")

    for attempt in range(RETRIES):
        ctx = await _make_context(browser)
        page = await ctx.new_page()
        try:
            found = await scrape_archive_page(page, url)
            total = await page_count(page) if want_count else None
            return found, total
        except Blocked as exc:
            print(f"  [dom] {exc} (attempt {attempt + 1}/{RETRIES})")
            if attempt + 1 < RETRIES:
                await _sleep_backoff(attempt)
        finally:
            await ctx.close()

    raise Blocked(f"page {page_num} still blocked after {RETRIES} attempts")


async def page_count(page) -> int:
    """Highest page number in the archive's pagination (1 if unpaginated)."""
    return await page.evaluate(
        """() => {
            const ns = [...document.querySelectorAll('.page-numbers')]
                .map(a => parseInt(a.textContent.trim()))
                .filter(n => !isNaN(n));
            return ns.length ? Math.max(...ns) : 1;
        }"""
    )


async def scrape_via_dom(browser) -> list[dict]:
    """Page through the category archive, a fresh context per page.

    Page 1 reports how many pages exist, and we fetch exactly that many. Nothing
    beyond the last page is ever requested, so there is no ambiguous empty page
    to misread, and any failure inside 1..N is a genuine block that raises
    rather than quietly returning a short list.
    """
    first, total = await _fetch_one_page(browser, 1, want_count=True)
    total = min(total or 1, MAX_PAGES)
    print(f"  Found {len(first)} products.  ({total} page(s) in this category)")

    seen: set[str] = set()
    products: list[dict] = []
    for rec in first:
        seen.add(rec["product_url"])
        products.append(rec)

    for page_num in range(2, total + 1):
        await asyncio.sleep(PAGE_DELAY)
        found, _ = await _fetch_one_page(browser, page_num, want_count=False)
        print(f"  Found {len(found)} products.")
        fresh = [p for p in found if p["product_url"] not in seen]
        seen.update(p["product_url"] for p in fresh)
        products.extend(fresh)

    return products


# ---------------------------------------------------------------------------

async def main(save: bool = False, force_dom: bool = False):
    async with async_playwright() as pw:
        browser = await pw.chromium.launch(
            headless=True,
            args=["--disable-blink-features=AutomationControlled"],
        )

        all_products = None
        if not force_dom:
            # Land on a real page first so Cloudflare issues its cookies, and so
            # the API fetch runs same-origin from a page it has already cleared.
            ctx = await _make_context(browser)
            page = await ctx.new_page()
            await page.goto(ARCHIVE_URL, wait_until="domcontentloaded", timeout=90_000)
            await page.wait_for_timeout(2000)
            all_products = await scrape_via_api(page)
            await ctx.close()

        if all_products is None:
            if not force_dom:
                print("\n" + "!" * 62)
                print("!! Store API unavailable — falling back to DOM scraping.")
                print("!! Expected on datacenter IPs: Cloudflare answers /wp-json")
                print("!! with 403 from GitHub Actions while allowing it locally.")
                print("!! A 403 here is normal in CI; anything else is worth a look.")
                print("!" * 62 + "\n")
            try:
                all_products = await scrape_via_dom(browser)
            except Blocked as exc:
                await browser.close()
                # Exit non-zero. run_pipeline treats a failed scrape as non-fatal
                # and moves on, which is right — but the category must be
                # reported as failed, never loaded as a truncated list.
                sys.exit(f"\nFAILED: {exc}\nRefusing to load a partial category.")

        await browser.close()

    if save:
        out_dir = Path("data/raw")
        out_dir.mkdir(parents=True, exist_ok=True)
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        out_path = out_dir / f"ezgadgets_headset_{timestamp}.json"
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(all_products, f, ensure_ascii=False, indent=2)
        print(f"\nSaved {len(all_products)} records -> {out_path}")

    in_stock = [p for p in all_products if p["in_stock"] and p["price_bdt"]]
    print(f"\nTotal: {len(all_products)} | In stock: {len(in_stock)}")
    if in_stock:
        cheapest = min(in_stock, key=lambda p: p["price_bdt"])
        print(f"Cheapest: {cheapest['name'][:70]}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Scrape EZ Gadgets Headset listings")
    parser.add_argument("--save", action="store_true")
    parser.add_argument("--dom", action="store_true",
                        help="Skip the Store API and scrape the category archive")
    args = parser.parse_args()
    asyncio.run(main(save=args.save, force_dom=args.dom))
